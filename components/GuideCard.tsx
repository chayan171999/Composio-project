import Link from "next/link";
import { BLOCKER_CHIP } from "@/lib/display";
import type { Guide } from "@/lib/schema";

export default function GuideCard({ guide }: { guide: Guide }) {
  const blocker = BLOCKER_CHIP[guide.verdict.blockerType];

  return (
    <Link
      href={`/guides/${guide.slug}`}
      className="block rounded-lg border border-gray-200 p-4 transition-colors hover:border-gray-400"
    >
      <div className="flex items-start justify-between gap-2">
        <p className="font-medium">{guide.appName}</p>
        <span className={`rounded-full px-2 py-0.5 text-xs ${blocker.className}`}>
          {blocker.label}
        </span>
      </div>
      <p className="mt-2 text-sm text-gray-600">
        Typically ready in {guide.verdict.readyIn.typical}
      </p>
      <div className="mt-2 flex flex-wrap items-center gap-2 text-xs text-gray-500">
        <span>Composio managed: {guide.composio.managedOAuth}</span>
        <span>·</span>
        <span>Difficulty {guide.verdict.difficulty}/5</span>
      </div>
      {guide.generatedBy === "agent" && (
        <p className="mt-2 text-xs text-gray-400">
          Generated by agent on {guide.lastChecked}
        </p>
      )}
    </Link>
  );
}
