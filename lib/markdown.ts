import type { Claim, Guide } from "./schema";

const STATUS_LABEL: Record<Claim["status"], string> = {
  tested: "Tested",
  sourced: "Sourced",
  inferred: "Inferred",
  unverified: "Unverified",
};

export function guideToMarkdown(guide: Guide): string {
  const evidence = (ids: string[]) =>
    ids.length > 0 ? ` _[${ids.join(", ")}]_` : "";

  const lines: string[] = [
    `# ${guide.appName} — bring your own OAuth app`,
    "",
    `**${guide.verdict.oneLiner}**`,
    "",
    `- Blocker: \`${guide.verdict.blockerType}\` · Difficulty ${guide.verdict.difficulty}/5`,
    `- Ready in — min ${guide.verdict.readyIn.min} · typical ${guide.verdict.readyIn.typical} · worst ${guide.verdict.readyIn.worst}`,
    `- Composio managed OAuth: ${guide.composio.managedOAuth}`,
    "",
    "## Do you need your own OAuth app?",
    ...guide.composio.whenToBringYourOwn.map((reason) => `- ${reason}`),
    "",
    "## Start today",
    ...guide.criticalPath.map(
      (item, i) => `${i + 1}. **${item.action}** — ${item.why}${evidence(item.claimIds)}`,
    ),
    "",
    "## While you wait",
    guide.beforeApproval.whatWorks,
    ...guide.beforeApproval.limits.map((limit) => `- ${limit}`),
    "",
    "## Steps",
    ...guide.steps.flatMap((step, i) => [
      `${i + 1}. **${step.title}** (${step.actor}${step.estTime ? `, ${step.estTime}` : ""})`,
      `   ${step.detail}`,
      ...(step.whyHuman ? [`   _Why human: ${step.whyHuman}_`] : []),
    ]),
    "",
    "## Config",
    `- Portal: ${guide.config.portalUrl}`,
    `- Redirect URI: ${guide.config.redirectUriNotes}`,
    ...(guide.config.scopes.length > 0
      ? [
          "",
          "| Scope | Purpose | Review level |",
          "| --- | --- | --- |",
          ...guide.config.scopes.map(
            (scope) => `| \`${scope.name}\` | ${scope.purpose} | ${scope.reviewLevel} |`,
          ),
        ]
      : []),
    "",
    "## Review & approval",
    `- Required when: ${guide.review.requiredWhen}`,
    ...guide.review.process.map((step) => `- ${step}`),
    `- Timeline: ${guide.review.timeline}`,
    `- Cost: ${guide.review.cost}`,
    `- Recurring: ${guide.review.recurring}`,
    "",
    "## Gotchas",
    ...guide.gotchas.map((gotcha) => `- ${gotcha.text}${evidence(gotcha.claimIds)}`),
    "",
    "## Hand off to Composio",
    ...guide.composioHandoff.map((step, i) => `${i + 1}. ${step}`),
    "",
    "## Evidence",
    ...guide.claims.map((claim) => {
      const sources = claim.sources.map((s) => `[${s.title}](${s.url})`).join(", ");
      return `- **${claim.id}** (${STATUS_LABEL[claim.status]}) ${claim.text}${
        sources ? ` — ${sources}` : ""
      }${claim.note ? ` _${claim.note}_` : ""}`;
    }),
  ];

  if (guide.openQuestions.length > 0) {
    lines.push("", "## Open questions", ...guide.openQuestions.map((q) => `- ${q}`));
  }

  lines.push(
    "",
    "---",
    `Last checked ${guide.lastChecked} · ${
      guide.generatedBy === "seed"
        ? "Hand-verified seed guide"
        : "Generated by agent — verify before relying on it"
    }`,
  );

  return lines.join("\n");
}
