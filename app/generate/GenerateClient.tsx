"use client";

import { useEffect, useRef, useState } from "react";
import GuideView from "@/components/GuideView";
import type { Guide } from "@/lib/schema";
import type { ProgressEvent } from "@/lib/agent/types";

type Line = { kind: "stage" | "fetch" | "warning"; text: string; ok?: boolean };

export default function GenerateClient({ query }: { query: string }) {
  const [lines, setLines] = useState<Line[]>([]);
  const [guide, setGuide] = useState<Guide | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [running, setRunning] = useState(true);
  const started = useRef(false);

  // No AbortController here on purpose: Strict Mode runs effects twice in dev, and
  // aborting on the simulated unmount would kill the single run the ref guard allows.
  // Letting it finish also avoids paying for a generation that gets thrown away.
  useEffect(() => {
    if (started.current) return;
    started.current = true;

    (async () => {
      try {
        const response = await fetch(`/api/generate?q=${encodeURIComponent(query)}`);
        if (!response.ok || !response.body) {
          setError((await response.text()) || `Request failed (${response.status})`);
          setRunning(false);
          return;
        }

        const reader = response.body.pipeThrough(new TextDecoderStream()).getReader();
        let buffer = "";

        while (true) {
          const { done, value } = await reader.read();
          if (done) break;
          buffer += value;

          const frames = buffer.split("\n\n");
          buffer = frames.pop() ?? "";

          for (const frame of frames) {
            const payload = frame.replace(/^data: /, "").trim();
            if (!payload) continue;

            const event = JSON.parse(payload) as ProgressEvent;
            if (event.type === "done") {
              setGuide(event.guide);
            } else if (event.type === "error") {
              setError(event.message);
            } else if (event.type === "fetch") {
              setLines((prev) => [
                ...prev,
                { kind: "fetch", text: event.url, ok: event.ok },
              ]);
            } else {
              setLines((prev) => [...prev, { kind: event.type, text: event.message }]);
            }
          }
        }
      } catch (err) {
        setError(err instanceof Error ? err.message : "Generation failed.");
      } finally {
        setRunning(false);
      }
    })();
  }, [query]);

  return (
    <main className="mx-auto max-w-3xl px-4 py-10">
      {!guide && (
        <>
          <h1 className="text-xl font-semibold">
            Generating a guide for &ldquo;{query}&rdquo;
          </h1>
          <ol className="mt-4 space-y-1.5 text-sm">
            {lines.map((line, i) => (
              <li key={i} className="flex gap-2">
                <span className="text-gray-400">
                  {line.kind === "fetch"
                    ? line.ok === undefined
                      ? "🔎"
                      : line.ok
                        ? "✅"
                        : "❌"
                    : line.kind === "warning"
                      ? "⚠️"
                      : "•"}
                </span>
                <span
                  className={
                    line.kind === "warning"
                      ? "text-amber-700"
                      : line.kind === "fetch"
                        ? "break-all font-mono text-xs text-gray-600"
                        : "text-gray-700"
                  }
                >
                  {line.text}
                </span>
              </li>
            ))}
          </ol>
          {running && <p className="mt-4 text-sm text-gray-400">Working…</p>}
        </>
      )}

      {error && (
        <div className="mt-6 rounded-md border border-rose-300 bg-rose-50 p-4 text-sm text-rose-800">
          {error}
        </div>
      )}

      {guide && (
        <>
          <p className="mb-4 rounded-md border border-amber-300 bg-amber-50 px-3 py-2 text-sm text-amber-800">
            Generated by agent. Not persisted yet — this URL is not shareable.
          </p>
          <GuideView guide={guide} />
        </>
      )}
    </main>
  );
}
