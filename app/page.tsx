import Link from "next/link";
import { redirect } from "next/navigation";
import GuideCard from "@/components/GuideCard";
import SearchBox from "@/components/SearchBox";
import { getAllGuides, matchGuide } from "@/lib/guides";

export default async function Home({
  searchParams,
}: {
  searchParams: Promise<{ q?: string }>;
}) {
  const { q } = await searchParams;
  const query = q?.trim();
  const guides = await getAllGuides();

  if (query) {
    const match = matchGuide(guides, query);
    if (match) redirect(`/guides/${match.slug}`);
  }

  const seeds = guides.filter((guide) => guide.generatedBy === "seed");
  const generated = guides.filter((guide) => guide.generatedBy === "agent");

  return (
    <main className="mx-auto max-w-3xl px-4 py-12">
      <h1 className="text-2xl font-semibold">
        Do you need your own OAuth app?
      </h1>
      <p className="mt-2 text-gray-600">
        Look up an app and find out in 30 seconds: whether Composio&apos;s managed
        OAuth is enough, how long approval takes, and what to start today.
      </p>

      <div className="mt-6">
        <SearchBox defaultValue={query ?? ""} />
      </div>

      {query && (
        <div className="mt-6 rounded-md border border-amber-300 bg-amber-50 px-4 py-3 text-sm">
          <p className="text-amber-900">
            No guide yet for <span className="font-medium">{query}</span>.
          </p>
          <Link
            href={`/generate?q=${encodeURIComponent(query)}`}
            className="mt-1 inline-block font-medium text-sky-700 underline"
          >
            Generate one →
          </Link>
        </div>
      )}

      <section className="mt-10">
        <h2 className="text-sm font-medium text-gray-500">Verified guides</h2>
        <div className="mt-3 grid gap-3 sm:grid-cols-2">
          {seeds.map((guide) => (
            <GuideCard key={guide.slug} guide={guide} />
          ))}
        </div>
      </section>

      {generated.length > 0 && (
        <section className="mt-8">
          <h2 className="text-sm font-medium text-gray-500">
            Generated by agent
          </h2>
          <div className="mt-3 grid gap-3 sm:grid-cols-2">
            {generated.map((guide) => (
              <GuideCard key={guide.slug} guide={guide} />
            ))}
          </div>
        </section>
      )}
    </main>
  );
}
