import Link from "next/link";
import { redirect } from "next/navigation";
import GuideCard from "@/components/GuideCard";
import SearchBox from "@/components/SearchBox";
import { getAllGuides, matchGuide } from "@/lib/guides";

export default async function Home({
  searchParams,
}: {
  searchParams: Promise<{ q?: string }>;
}) {
  const { q } = await searchParams;
  const query = q?.trim();
  const guides = await getAllGuides();

  if (query) {
    const match = matchGuide(guides, query);
    if (match) redirect(`/guides/${match.slug}`);
  }

  const seeds = guides.filter((guide) => guide.generatedBy === "seed");
  const generated = guides.filter((guide) => guide.generatedBy === "agent");

  return (
    <main className="mx-auto max-w-3xl px-5 py-16 sm:py-24">
      <h1 className="text-balance text-3xl font-semibold tracking-tight text-ink sm:text-4xl">
        Do you need your own OAuth app?
      </h1>
      <p className="mt-3 max-w-xl text-balance leading-relaxed text-ink-2">
        Look up any app and find out in 30 seconds whether Composio&apos;s managed
        OAuth is enough, how long approval really takes, and what you can start
        today.
      </p>

      <div className="mt-7">
        <SearchBox defaultValue={query ?? ""} />
        {/* Live generation is the main feature but was only discoverable by
            searching for something that happened to miss. */}
        <p className="mt-2 text-xs text-ink-3">
          Not in the library? An agent researches the provider&apos;s own docs and
          writes the guide live — about a minute.
        </p>
      </div>

      {query && (
        <div className="mt-5 rounded-lg border border-edge bg-sunken px-4 py-4">
          <p className="text-sm text-ink-2">
            No guide yet for <span className="font-medium text-ink">{query}</span>.
          </p>
          <Link
            href={`/generate?q=${encodeURIComponent(query)}`}
            className="mt-3 inline-flex items-center gap-2 rounded-md bg-ink px-3 py-2 text-xs font-medium text-bg transition-opacity hover:opacity-85"
          >
            Research it and build a guide
            <span className="opacity-60">~1 min</span>
          </Link>
        </div>
      )}

      <GuideGrid
        label="Hand-verified"
        hint="Researched and checked against primary sources"
        guides={seeds}
      />
      {generated.length > 0 && (
        <GuideGrid
          label="Generated by agent"
          hint="Machine-extracted — check the evidence before relying on it"
          guides={generated}
        />
      )}
    </main>
  );
}

function GuideGrid({
  label,
  hint,
  guides,
}: {
  label: string;
  hint: string;
  guides: Awaited<ReturnType<typeof getAllGuides>>;
}) {
  return (
    <section className="mt-12">
      <div className="flex flex-wrap items-baseline justify-between gap-2">
        <h2 className="text-sm font-semibold uppercase tracking-wide text-ink">
          {label}
        </h2>
        <p className="text-xs text-ink-3">{hint}</p>
      </div>
      <div className="mt-4 grid gap-3 sm:grid-cols-2">
        {guides.map((guide) => (
          <GuideCard key={guide.slug} guide={guide} />
        ))}
      </div>
    </section>
  );
}
